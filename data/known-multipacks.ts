/**
 * Boxes we know exist, and what is inside them.
 *
 * ── Why a box needs saying at all ─────────────────────────────────────────
 *
 * A variety pack carries one barcode outside and a different one on each item
 * inside. A cat food box of three recipes is four codes, and only three of them
 * name something anybody eats.
 *
 * Leaving the fourth out of the catalog is not neutral. An unknown code opens
 * the discovery screen in the consumer app — "photograph the ingredients and
 * this product exists" — and somebody does exactly that, photographing the back
 * of the box, where every member's list is printed one after another. What
 * comes back parses like an ingredient list, fingerprints like one and scores
 * like one, and describes no product on earth. Nothing downstream can catch it,
 * because by every test available it IS an ingredient list.
 *
 * So the box is marked on purpose: `found = false`, `reason = 'multipack'`, and
 * its members in `contains`. That is migration 0022 in the consumer repository,
 * and `app/api/multipack/route.ts` is an operator standing in a shop doing it
 * one box at a time. This file is the same fact arriving in bulk from research,
 * and the import route writes both the same way.
 *
 * ── Why this is a separate list and not a `scope` on KnownPackage ─────────
 *
 * Because of what is NOT in this interface. A `KnownProduct` is a recipe: it
 * has `packages`, and every one of them resolves to a composition in
 * `data/known-formulas.ts`. Filing a box there would have made "this row must
 * never be written with an ingredient list" a rule somebody has to remember —
 * a filter in the import route, correct on the day it was written and one
 * refactor away from silently writing the back of a carton into the catalog as
 * a product.
 *
 * Here it is not a rule. There is no field to put a composition in, no formula
 * keyed by a box's barcode, and nothing that reads this file has a composition
 * to offer. The guarantee is structural, which is the only kind that survives.
 *
 * The variety packs make the same point from the other side: seventeen of the
 * boxes below hold three DIFFERENT recipes, so there is no single formula they
 * could carry even in principle.
 *
 * ── Members are recorded, not joined to ───────────────────────────────────
 *
 * A member code need not be a product we hold. The research reads all four
 * codes off one box in one pass, long before every tin has been verified — and
 * three of the boxes below name a tin this seed deliberately holds back (see
 * section I of docs/CATALOG-CONFLICTS.md). Recording the relation anyway is
 * what lets the app tell the next person which member is still unread, and that
 * person is the one holding the tin.
 */

export interface KnownMultipack {
  brand: string;
  /** The range within the brand, matching data/us-pet-brands.ts. */
  line: string;
  /**
   * What is on the box, minus the range: a flavour for a single-recipe case,
   * the assortment's own name for a variety pack ("Ninja Cat Jiu Jit Stew").
   */
  variant: string;
  species: "cat" | "dog";
  /** The whole box as printed: "3 OZ CAN (24 PACK)". */
  size: string;
  container: "box" | "bag" | "tray";
  /** As printed under the bars. A case is often a GTIN-14 — see `gs1Body`. */
  upc: string;
  /** How many units inside, where the box says. */
  packCount: number | null;
  /** One unit as printed on the box: "3 oz can". */
  unitSize: string | null;
  /**
   * Member barcodes, as printed under their own bars.
   *
   * Empty is an ordinary answer and means exactly one thing: the box was read
   * and no inner code could be proven. It is never a guess — a member invented
   * to fill this in would send a shopper to a product that does not exist.
   */
  contains: string[];
}

